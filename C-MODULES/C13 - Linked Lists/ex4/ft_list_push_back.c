#include "ft_list.h"

void	ft_list_push_back(t_list **begin_list, void *data)
{
	t_list	*new;
	t_list	*tmp;

	new = ft_create_elem(data);
	if (!new)
		return ;
	if (!*begin_list)
	{
		*begin_list = new;
		return ;
	}
	tmp = *begin_list;
	while (tmp && tmp->next)
		tmp = tmp->next;
	tmp->next = new;
}
